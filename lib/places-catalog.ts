export function youtubeSearch(keyword: string, shorts = false) {
  const q = shorts ? `${keyword} 여행 #shorts` : `${keyword} 여행 브이로그`;
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(q)}`;
}

export function mapsSearch(place: { lat: number | null; lng: number | null; name: string; address?: string }) {
  if (place.lat != null && place.lng != null) {
    return `https://www.google.com/maps/search/?api=1&query=${place.lat},${place.lng}`;
  }
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(place.address || place.name)}`;
}
